const english = Object.fromEntries(Object.keys(filipino).map((phrase) => [phrase, phrase]));
const dictionaries = { en: english, fil: filipino };
let activeLanguage = 'en';
let observer = null;
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const translatableAttributes = ['placeholder', 'title', 'aria-label', 'aria-description'];

function translateNotification(text) {
  if (activeLanguage !== 'fil') return text;
  let match = text.match(/^Open notification: (.*)$/);
  if (match) return `Buksan ang notipikasyon: ${translateNotification(match[1])}`;
  match = text.match(/^New notification: (.*)$/);
  if (match) return `Bagong notipikasyon: ${translateNotification(match[1])}`;
  match = text.match(/^You have (\d+) new notifications?\.$/);
  if (match) return `May ${match[1]} bagong notipikasyon ka.`;
  match = text.match(/^Book an appointment for (.+)$/);
  if (match) return `Magpa-appointment para sa ${match[1]}`;
  match = text.match(/^(.+) · (Pending|Approved|Rescheduled|Cancelled|Completed)$/i);
  if (match) return `${match[1]} · ${translateText(match[2].charAt(0).toUpperCase() + match[2].slice(1).toLowerCase())}`;
  match = text.match(/^Appointment booked for (.+) is pending approval\.$/);
  if (match) return `Naghihintay ng pag-apruba ang appointment sa ${match[1]}.`;
  match = text.match(/^Your appointment on (.+) has been cancelled\.$/);
  if (match) return `Nakansela ang iyong appointment sa ${match[1]}.`;
  match = text.match(/^Your appointment on (.+) is marked completed\.$/);
  if (match) return `Minarkahang nakumpleto ang iyong appointment sa ${match[1]}.`;
  match = text.match(/^Your appointment on (.+) has been approved\.$/);
  if (match) return `Naaprubahan ang iyong appointment sa ${match[1]}.`;
  match = text.match(/^Book (.+) on (.+) at (.+)\?$/);
  if (match) return `I-book ang ${match[1]} sa ${match[2]} nang ${match[3]}?`;
  return text;
}

export function translateText(value) {
  if (typeof value !== 'string') return value;
  const trimmed = value.trim();
  const table = dictionaries[activeLanguage] || dictionaries.en;
  const translated = table[trimmed] ?? translateNotification(trimmed);
  return value.replace(trimmed, translated);
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const displayed = node.nodeValue || '';
    let state = originalText.get(node);
    if (!state) {
      state = { source: displayed, rendered: displayed };
      originalText.set(node, state);
    } else if (displayed !== state.rendered) {
      state.source = displayed;
    }
    const source = state.source;
    const translated = translateText(source);
    state.rendered = translated;
    if (translated !== displayed) node.nodeValue = translated;
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE) return;
  const element = node;
  if (!originalAttributes.has(element)) originalAttributes.set(element, new Map());
  const attributes = originalAttributes.get(element);
  for (const attribute of translatableAttributes) {
    if (!element.hasAttribute(attribute)) continue;
    const displayed = element.getAttribute(attribute);
    if (!attributes.has(attribute)) attributes.set(attribute, { source: displayed, rendered: displayed });
    const state = attributes.get(attribute);
    if (displayed !== state.rendered) state.source = displayed;
    const source = state.source;
    const translated = translateText(source);
    state.rendered = translated;
    if (translated !== displayed) element.setAttribute(attribute, translated);
  }
  for (const child of element.childNodes) translateNode(child);
}

export function setLanguage(language) {
  activeLanguage = Object.hasOwn(dictionaries, language) ? language : 'en';
  document.documentElement.lang = activeLanguage === 'fil' ? 'fil' : 'en';
  translateNode(document.body);
  document.dispatchEvent(new CustomEvent('clinic-language-change', { detail: { language: activeLanguage } }));
  return activeLanguage;
}

export function getLanguage() { return activeLanguage; }
export function t(phrase) { return dictionaries[activeLanguage]?.[phrase] ?? phrase; }

export function startLocalization() {
  if (observer || !document.body) return;
  setLanguage(activeLanguage);
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target);
      else record.addedNodes.forEach(translateNode);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true });
}

export function translationCoverage() {
  return { english: Object.keys(dictionaries.en).length, filipino: Object.keys(dictionaries.fil).length,
    missingInFilipino: Object.keys(dictionaries.en).filter((key) => !(key in dictionaries.fil)),
    missingInEnglish: Object.keys(dictionaries.fil).filter((key) => !(key in dictionaries.en)) };
}

if (typeof document !== 'undefined') startLocalization();
